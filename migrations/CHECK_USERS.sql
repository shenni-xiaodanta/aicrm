-- CHECK_USERS.sql — 查看现有登录账号（只读，随时可跑，AI 不直接连库）
-- 用途：想用已有账号做越权回归时，先看看有哪些用户名
-- 注意：password 列是 bcrypt 哈希，不可逆，这里只列元信息
